"""Draft artifacts: PR description, release notes, Medium/Discord/Slack.

All artifacts are drafts written from the run's own evidence. Posting,
merging, deploying, or sending channel messages is out of scope for v1:
`external --dry-run` shows what *would* happen; anything else needs an
explicit approval policy (see external.py).
"""
from __future__ import annotations


def pr_description(state: dict, profile: dict, summary: str) -> str:
    steps = state["steps"]
    verified = ", ".join(
        f"{s}@{state['verifiedCommits'].get(s, '?')[:8]}"
        for s in ("reproduce", "review", "e2e")
        if steps[s]["status"] == "done"
    )
    return f"""# {state['title'] or ('Fixes #' + state['issue'])}

Fixes {profile['github']}#{state['issue']}.

## Summary
{summary or '(see run evidence)'}

## Verification ({state['id']})
- Base commit: {state['baseCommit'][:12] if state['baseCommit'] else '?'}
- Work commit: {state['workCommit'][:12] if state['workCommit'] else '?'}
- Verified steps: {verified or '(none passed yet)'}

## Evidence
Run dir (local, not committed to target repo): see `openmainty status --run {state['id']}`.
{suggest_labels(profile)}
"""


def suggest_labels(profile: dict) -> str:
    labels = (profile.get("labels", {}) or {}).get("pr", [])
    if not labels:
        return ""
    return "\nSuggested labels: " + ", ".join(f"`{l}`" for l in labels) + "\n"


def release_notes(state: dict, profile: dict, summary: str) -> str:
    return f"""# Release notes draft ({profile['name']}#{state['issue']})

{summary or '(pending fix summary)'}

- Scope: per-package notes to be split by maintainer at release time.
- Procedure: {profile.get('release', {}).get('notes', '(see repo release docs)')}
- Run: {state['id']} @ {state['workCommit'][:12] if state['workCommit'] else '?'}
"""


def medium_draft(state: dict, summary: str) -> str:
    return f"""# Medium draft: fixing {state['repo']}#{state['issue']}

## Outline
1. The report: {state['title']}
2. Root cause (one paragraph).
3. The fix and regression test.
4. Verification evidence.

## Body sketch
{summary or '(pending fix summary)'}

> Draft generated by OpenMainty run {state['id']}; human review required before publishing.
"""


def discord_draft(state: dict) -> str:
    return (
        f"Fix for {state['repo']}#{state['issue']} "
        f"({state['title'] or 'see issue'}) is in review — "
        f"run {state['id']}. Feedback welcome on the PR."
    )


def slack_draft(state: dict) -> str:
    return (
        f"[openmainty] {state['repo']}#{state['issue']} "
        f"{state['title'] or ''} — run {state['id']}, "
        f"work commit {(state['workCommit'] or '?')[:12]}. Drafts ready for review."
    )
